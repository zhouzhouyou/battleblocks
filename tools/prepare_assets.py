from PIL import Image
import json, shutil
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets"
OUT.mkdir(exist_ok=True)

def webp_durations(path):
    """Read ANMF frame durations; Pillow does not expose them in info."""
    data = path.read_bytes()
    assert data[:4] == b"RIFF" and data[8:12] == b"WEBP", path
    pos, durations = 12, []
    while pos + 8 <= len(data):
        fourcc = data[pos:pos+4]
        size = int.from_bytes(data[pos+4:pos+8], "little")
        if fourcc == b"ANMF":
            durations.append(int.from_bytes(data[pos+8+12:pos+8+15], "little") / 1000)
        pos += 8 + size + (size & 1)
    return durations

for name in ("balanced", "hp", "damage", "mp", "hd", "hm", "dm"):
    Image.open(ROOT / f"asset-sources/{name}.webp").convert("RGBA").save(OUT / f"{name}.webp", lossless=True, exact=True, method=6)
shutil.copy2(ROOT / "asset-sources/crush.wav", OUT / "crush.wav")
report = {}
for name in ("knight", "elf", "wizzard", "goblin", "imp", "chort", "big_zombie", "big_demon_ro"):
    source = ROOT / f"asset-sources/{name}.webp"
    gif = Image.open(source)
    frame_durations = webp_durations(source)
    assert len(frame_durations) == gif.n_frames, (name, len(frame_durations), gif.n_frames)
    frames, durations = [], []
    bounds = None
    for i in range(gif.n_frames):
        gif.seek(i)
        frame = gif.convert("RGBA")
        # Hidden RGB under alpha=0 does not contribute to the rendered image.
        frame.putdata([pixel if pixel[3] else (0,0,0,0) for pixel in frame.get_flattened_data()])
        frames.append(frame.copy())
        durations.append(frame_durations[i])
        b = frame.getbbox()
        if b:
            bounds = b if bounds is None else (min(bounds[0], b[0]), min(bounds[1], b[1]), max(bounds[2], b[2]), max(bounds[3], b[3]))
    bounds = bounds or (0, 0, 1, 1)
    unique, indices, hashes = [], [], {}
    for frame in frames:
        crop = frame.crop(bounds)
        key = crop.tobytes()
        if key not in hashes:
            hashes[key] = len(unique)
            unique.append(crop)
        indices.append(hashes[key])
    w, h = unique[0].size
    atlas = Image.new("RGBA", (w * len(unique), h))
    for i, frame in enumerate(unique): atlas.paste(frame, (i * w, 0))
    for original, index in zip(frames, indices):
        restored = Image.new("RGBA", original.size)
        restored.paste(unique[index], (bounds[0], bounds[1]))
        assert restored.tobytes() == original.tobytes(), f"Frame mismatch: {name}"
    atlas.save(OUT / f"{name}.webp", lossless=True, exact=True, method=6)
    meta = {"original_size": list(gif.size), "bounds": list(bounds), "frame_size": [w,h], "indices": indices, "durations": durations}
    (OUT / f"{name}.json").write_text(json.dumps(meta, indent=2))
    report[name] = {**meta, "unique_frames": len(unique), "original_rgba_bytes": gif.width * gif.height * 4 * len(frames), "atlas_rgba_bytes": atlas.width * atlas.height * 4, "atlas_webp_bytes": (OUT / f"{name}.webp").stat().st_size}
(OUT / "report.json").write_text(json.dumps(report, indent=2))
print(json.dumps(report, indent=2))

