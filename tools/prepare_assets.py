from pathlib import Path
from PIL import Image
import json, shutil
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets"
OUT.mkdir(exist_ok=True)
for name in ("balanced", "hp", "damage", "mp", "hd", "hm", "dm"):
    shutil.copy2(ROOT / f"asset-sources/{name}.png", OUT / f"{name}.png")
shutil.copy2(ROOT / "asset-sources/crush.wav", OUT / "crush.wav")
report = {}
for name in ("knight", "elf", "wizzard", "goblin", "imp", "chort", "big_zombie", "big_demon_ro"):
    source = ROOT / f"asset-sources/{name}.gif"
    gif = Image.open(source)
    frames, durations = [], []
    bounds = None
    for i in range(gif.n_frames):
        gif.seek(i)
        frame = gif.convert("RGBA")
        # Hidden RGB under alpha=0 does not contribute to the rendered image.
        frame.putdata([pixel if pixel[3] else (0,0,0,0) for pixel in frame.getdata()])
        frames.append(frame.copy())
        durations.append(gif.info.get("duration", 100) / 1000)
        b = frame.getbbox()
        if b:
            bounds = b if bounds is None else (min(bounds[0], b[0]), min(bounds[1], b[1]), max(bounds[2], b[2]), max(bounds[3], b[3]))
    bounds = bounds or (0, 0, 1, 1)
    unique, indices, hashes = [], [], {}
    for frame in frames:
        crop = frame.crop(bounds)
        key = crop.tobytes()
        if key not in hashes:
            hashes[key] = len(unique)
            unique.append(crop)
        indices.append(hashes[key])
    w, h = unique[0].size
    atlas = Image.new("RGBA", (w * len(unique), h))
    for i, frame in enumerate(unique): atlas.paste(frame, (i * w, 0))
    for original, index in zip(frames, indices):
        restored = Image.new("RGBA", original.size)
        restored.paste(unique[index], (bounds[0], bounds[1]))
        assert restored.tobytes() == original.tobytes(), f"Frame mismatch: {name}"
    atlas.save(OUT / f"{name}.png", optimize=True)
    meta = {"original_size": list(gif.size), "bounds": list(bounds), "frame_size": [w,h], "indices": indices, "durations": durations}
    (OUT / f"{name}.json").write_text(json.dumps(meta, indent=2))
    report[name] = {**meta, "unique_frames": len(unique), "original_rgba_bytes": gif.width * gif.height * 4 * len(frames), "atlas_rgba_bytes": atlas.width * atlas.height * 4, "atlas_png_bytes": (OUT / f"{name}.png").stat().st_size}
(OUT / "report.json").write_text(json.dumps(report, indent=2))
print(json.dumps(report, indent=2))

rows=[]
for name,meta in report.items():
    w,h=meta["frame_size"]
    rows.append(f'    SpriteAsset {{ bytes: include_bytes!("../assets/{name}.png"), w: {w}., h: {h}., durations: &{meta["durations"]}, indices: &{meta["indices"]} }},')
(ROOT / "src/sprites.rs").write_text("// Generated by tools/prepare_assets.py\nuse super::SpriteAsset;\npub const SPRITES: &[SpriteAsset] = &[\n"+"\n".join(rows)+"\n];\n")

# Approved small awakening skins use the existing PNG decoder and one source frame.
awake_rows=[]
for name in ["knight","elf","wizard","goblin","imp","chort","zombie"]:
    path=OUT/"awakened"/(name+"-awakening.png")
    w,h=Image.open(path).size
    awake_rows.append(f'    SpriteAsset {{ bytes: include_bytes!("../assets/awakened/{name}-awakening.png"), w: {w}., h: {h}., durations: &[1.], indices: &[0] }},')
with (ROOT/"src/sprites.rs").open("a") as generated:
    generated.write("\npub const AWAKENED: &[SpriteAsset] = &[\n"+"\n".join(awake_rows)+"\n];\n")

# Tiny roster thumbnails keep full-size textures limited to the selected hero.
thumbs = Image.new("RGBA", (280, 48))
for i, (name, meta) in enumerate(list(report.items())[:7]):
    w, h = meta["frame_size"]
    image = Image.open(OUT / f"{name}.png").crop((0, 0, w, h))
    image.thumbnail((40, 48), Image.Resampling.NEAREST)
    thumbs.paste(image, (i * 40 + (40 - image.width) // 2, 48 - image.height))
thumbs.save(OUT / "hero-thumbnails.png", optimize=True)
